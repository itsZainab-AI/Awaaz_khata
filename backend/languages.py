def get_template(language: str, key: str, **kwargs: str) -> str:
    fallback = LANGUAGES["hi-en"]["templates"]
    template = LANGUAGES.get(language, LANGUAGES["hi-en"])["templates"].get(key)
    if template is None:
        template = fallback.get(key)
    if template is None:
        raise KeyError(f"Unknown language template: {key}")
    return template.format(**kwargs)
